"""Convert MCQ.txt into js/questions.js for the Yalda Night Quiz.

MCQ.txt format (blank line between questions):

    1- Question text?
    Option A
    Option B Correct
    Option C
    Option D

Mark the right option by ending its line with the word "Correct".
The output is lightly encoded so the answers are not readable at a glance
in the public GitHub repository (this is obfuscation, not real security).

Usage:  python tools/build_questions.py [MCQ.txt] [js/questions.js]
"""
import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "MCQ.txt"
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "js" / "questions.js"

KEY = "yalda-shab-e-chelleh"

blocks = re.split(r"\n\s*\n", src.read_text(encoding="utf-8").strip())
questions = []
for block in blocks:
    lines = [l.strip() for l in block.strip().splitlines() if l.strip()]
    if len(lines) < 3:
        continue
    text = re.sub(r"^\d+\s*[-.)]\s*", "", lines[0])
    options, answer = [], None
    for i, line in enumerate(lines[1:]):
        m = re.match(r"^(.*?)\s+correct\s*$", line, re.I)
        if m:
            answer = i
            line = m.group(1)
        options.append(line)
    if answer is None:
        print(f"WARNING: no correct answer marked for: {text!r}", file=sys.stderr)
        answer = -1
    questions.append({"q": text, "o": options, "a": answer})

raw = json.dumps(questions, ensure_ascii=False).encode("utf-8")
key = KEY.encode()
enc = base64.b64encode(bytes(b ^ key[i % len(key)] for i, b in enumerate(raw))).decode()

dst.write_text(
    "// Generated by tools/build_questions.py from MCQ.txt. Do not edit by hand.\n"
    f'window.QUIZ_DATA = "{enc}";\n',
    encoding="utf-8",
)
print(f"Wrote {len(questions)} questions to {dst}")
